// Regenerates the LNDC logo from the Oswald Bold glyphs: `node scripts/build-logo.mjs`.
// Writes the inline-SVG paths used by Logo.astro, plus the favicon set in public/.
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';
import sharp from 'sharp';

const fontFile = readFileSync('node_modules/@fontsource/oswald/files/oswald-latin-700-normal.woff');
const font = opentype.parse(fontFile.buffer.slice(fontFile.byteOffset, fontFile.byteOffset + fontFile.byteLength));

// Glyphs are placed by hand: opentype.js can't run Oswald's GSUB features.
function lettersPath() {
  const path = new opentype.Path();
  let x = 0;
  for (const ch of 'LNDC') {
    const g = font.charToGlyph(ch);
    path.extend(g.getPath(x, 0, 100));
    x += (g.advanceWidth / font.unitsPerEm) * 100 + 2.5;
  }
  return path;
}
const raw = lettersPath();
const bb = raw.getBoundingBox();

// Fit the letters inside the triangle, above the book.
const box = { x: 68, y: 114, w: 104, h: 52 };
const s = Math.min(box.w / (bb.x2 - bb.x1), box.h / (bb.y2 - bb.y1));
const tx = box.x + (box.w - (bb.x2 - bb.x1) * s) / 2 - bb.x1 * s;
const ty = box.y + (box.h - (bb.y2 - bb.y1) * s) / 2 - bb.y1 * s;
const letters = lettersPath();
letters.commands.forEach((c) => {
  for (const [kx, ky] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
    if (c[kx] !== undefined) {
      c[kx] = c[kx] * s + tx;
      c[ky] = c[ky] * s + ty;
    }
  }
});

const paths = {
  viewBox: '0 0 240 216',
  triangle: 'M120 12 L16 196 L224 196 Z',
  letters: letters.toPathData(2),
  bookLeft: 'M120 182 C100 166 60 163 16 172 L24 206 C60 196 97 198 120 213 Z',
  bookRight: 'M120 182 C140 166 180 163 224 172 L216 206 C180 196 143 198 120 213 Z',
  // Page lines are cut out of the book with a mask so the logo works on any background.
  pageLines: [
    'M116 187 C96 175 62 172 21 180',
    'M116 194 C96 182 62 180 23 188',
    'M116 201 C96 190 62 188 25 196',
    'M124 187 C144 175 178 172 219 180',
    'M124 194 C144 182 178 180 217 188',
    'M124 201 C144 190 178 188 215 196',
  ],
};

writeFileSync(
  'src/components/logo-paths.ts',
  `// Generated by scripts/build-logo.mjs — edit the script, not this file.\nexport const logo = ${JSON.stringify(paths, null, 2)} as const;\n`,
);

const svg = (color, bg) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 -4 256 228">
${bg ? `<rect x="-8" y="-4" width="256" height="228" rx="40" fill="${bg}"/>` : ''}
<defs><mask id="m"><rect x="-8" y="-4" width="256" height="228" fill="#fff"/>${paths.pageLines.map((d) => `<path d="${d}" stroke="#000" stroke-width="2.6" fill="none" stroke-linecap="round"/>`).join('')}</mask></defs>
<path d="${paths.triangle}" fill="none" stroke="${color}" stroke-width="9" stroke-linejoin="round"/>
<path d="${paths.letters}" fill="${color}"/>
<g mask="url(#m)" fill="${color}"><path d="${paths.bookLeft}"/><path d="${paths.bookRight}"/></g>
</svg>`;

writeFileSync('public/favicon.svg', svg('#0A96EE'));
writeFileSync('src/assets/logo.svg', svg('#0A96EE'));
const tile = Buffer.from(svg('#FFFFFF', '#0679C7'));
await sharp(tile, { density: 400 }).resize(180, 180).png().toFile('public/apple-touch-icon.png');
await sharp(tile, { density: 400 }).resize(512, 512).png().toFile('public/icon-512.png');
await sharp(Buffer.from(svg('#0A96EE')), { density: 400 }).resize(32, 32, { fit: 'contain', background: '#ffffff00' }).png().toFile('public/favicon-32.png');
console.log('logo written', { scale: s.toFixed(3) });
